#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Owtlet environment synchronizer (scripts/sync-env.sh)
# Copies the root .env (created from .env.example if missing) into the single
# Next.js app: development/frontend/.env  (read by Next.js and Prisma).
# The template's backend (NestJS) and mobile (Flutter) apps were removed (ADR-015).
# ==============================================================================

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

SOURCE_ENV=".env"
APP_DIR="development/frontend"

if [ ! -f "$SOURCE_ENV" ]; then
  if [ -f ".env.example" ]; then
    echo "ℹ️  Root .env not found. Initializing .env from .env.example..."
    cp .env.example .env
  else
    echo "❌ Error: Neither .env nor .env.example found in root directory!"
    exit 1
  fi
fi

if [ ! -d "$APP_DIR" ]; then
  echo "❌ Error: $APP_DIR not found."
  exit 1
fi

{
  echo "# Auto-generated by scripts/sync-env.sh from root .env — edit the root .env instead"
  grep -Ev '^[[:space:]]*(#|$)' "$SOURCE_ENV"
} > "$APP_DIR/.env"

echo "  ✅ Synced: $APP_DIR/.env ($(grep -Evc '^[[:space:]]*(#|$)' "$SOURCE_ENV") keys)"
if grep -q "change_me" "$SOURCE_ENV"; then
  echo "  ⚠️  Some secrets still contain 'change_me' — replace them before staging/production."
fi
echo "🎉 SUCCESS: environment ready for the Owtlet Next.js app (http://localhost:3000, API at /api)."
