#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Owtlet environment synchronizer (scripts/sync-env.sh)
# Copies the root .env into both:
#  - development/frontend/.env  (Next.js)
#  - development/backend/.env   (NestJS)
# ==============================================================================

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

SOURCE_ENV=".env"

if [ ! -f "$SOURCE_ENV" ]; then
  if [ -f ".env.example" ]; then
    echo "ℹ️  Root .env not found. Initializing .env from .env.example..."
    cp .env.example .env
  else
    echo "❌ Error: Neither .env nor .env.example found in root directory!"
    exit 1
  fi
fi

sync_to() {
  local target_dir="$1"
  if [ -d "$target_dir" ]; then
    {
      echo "# Auto-generated by scripts/sync-env.sh from root .env — edit the root .env instead"
      grep -Ev '^[[:space:]]*(#|$)' "$SOURCE_ENV"
    } > "$target_dir/.env"
    echo "  ✅ Synced: $target_dir/.env ($(grep -Evc '^[[:space:]]*(#|$)' "$SOURCE_ENV") keys)"
  fi
}

sync_to "development/frontend"
sync_to "development/backend"

if grep -q "change_me" "$SOURCE_ENV"; then
  echo "  ⚠️  Some secrets still contain 'change_me' — replace them before staging/production."
fi
echo "🎉 SUCCESS: environment synced across frontend and backend."
